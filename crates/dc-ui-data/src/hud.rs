    fn view_reads_set_n_then_set_0_and_packs_colours() {
        let keys = HudKeys::placeholder();
        let names = crate::UiNames::placeholder();
        let set0 = names.hud_set0.clone();
        let set1 = format!("{}1", names.hud_prefix);
        let text = format!(
            "[{set0}]\n{} = (10,20)\n{} = <255.0, 128.5, -3.0>\n{} = 0.5\n{} = 7\n{} = \"a\\b.dtx\"\n[{set1}]\n{} = (1,2)\n",
            keys.key(HudKey::FeedPos),
            keys.key(HudKey::SameTeamColour),
            keys.key(HudKey::SameTeamAlpha),
            keys.key(HudKey::FeedLineStep),
            keys.key(HudKey::FeedHeadIcon),
            keys.key(HudKey::FeedPos),
        );
        let t = LayoutTable::parse(&text, names);
        let v0 = HudView::new(&t, &keys, 0);
        let v1 = HudView::new(&t, &keys, 1);
        assert_eq!(v0.pair(HudKey::FeedPos), Some([10, 20]));
        assert_eq!(v1.pair(HudKey::FeedPos), Some([1, 2]));
        assert_eq!(v1.int(HudKey::FeedLineStep), Some(7), "falls back to set 0");
        assert_eq!(v0.int(HudKey::FeedPos), None, "wrong form");
        assert_eq!(v0.text(HudKey::FeedHeadIcon), Some("a\\b.dtx"));
        assert_eq!(
            v0.rgba(HudKey::SameTeamColour, Some(HudKey::SameTeamAlpha)),
            Some([255, 128, 0, 127])
        );
        assert_eq!(
            v0.rgba(HudKey::SameTeamColour, None),
            Some([255, 128, 0, 255])
        );
        assert_eq!(v0.pair(HudKey::BoardPos), None);
        assert!(keys.literal(HudLiteral::ClockDigits).contains("%d"));
    }
