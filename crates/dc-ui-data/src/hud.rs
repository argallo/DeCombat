impl HudKey {
    /// Number of keys.
    pub const COUNT: usize = 121 + Self::EXTRA_COUNT;
    /// Keys added by client-hud2 (68), client-nametags (15) and dserver-killforms (34), client-hudgaps (32), client-fixes5 (2),
    /// ffa-fixes9 (15), modes-r11 (16), match-r11a (6: the respawn gauge caps), modes-r11 CTF (22), modes-r11b
    /// Search and Destroy (21), modes-r11b Quarantine (26), modes-polish Quarantine (22), modes-polish
    /// Capture the Flag (12), modes-spyhunt Spy Hunt (47), ctf-clan-r12 flag marker texts (4), modes-r12b
    /// Quarantine round pictures (2), class-13 top and team-change sprite (18), modes-r13 host timer scale (1),
    /// doors-gear-r13 door prompt (3), match-r15 item prompt (3).
    pub const EXTRA_COUNT: usize = 369;

    /// Every key in table order.
    pub fn all() -> impl Iterator<Item = HudKey> {
        TABLE.iter().map(|t| t.0).chain(EXTRA.iter().map(|t| t.0))
    }

    fn row(self) -> (HudKey, u32, &'static str, usize, u32, ValueKind, HudSection) {
        let i = self as usize;
        match TABLE.get(i) {
            Some(r) => (r.0, r.1, r.2, r.3, r.4, r.5, HudSection::Set),
            None => EXTRA[i - TABLE.len()],
        }
    }

    /// The layout section the key is read from.
    pub fn section(self) -> HudSection {
        self.row().6
    }

    /// The pinned literal of the key.
    pub fn pin(self) -> Pin {
        let r = self.row();
        Pin {
            what: "HUD layout key",
            rva: r.1,
            sha16: r.2,
            len: r.3,
        }
    }

    /// Rva of the code that reads the key (the evidence of the pin).
    pub fn evidence(self) -> u32 {
        self.row().4
    }

    /// The value form the client's getter expects.
    pub fn kind(self) -> ValueKind {
        self.row().5
    }
}

/// Code literals of the HUD elements (not layout keys).
