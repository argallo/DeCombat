/// Where a key lives: the numbered HUD layout set (set N, else set 0) or a named section of the layout table.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum HudSection {
    Set,
    /// The HiSec section. EVIDENCE: cshell+0x98ab0, cshell+0x9a860 (section literal pushed with each key)
    HiSec,
    /// The miscellaneous section. EVIDENCE: cshell+0x1c3670 (section literal pushed with the key)
    Misc,
    /// The infection mode's section. EVIDENCE: cshell+0xb29c0 (section literal pushed with each key)
    Quarantine,
    /// The Spy Hunt section. EVIDENCE: cshell+0x70880 (section literal pushed with each key)
    SpyHunt,
}

impl HudSection {
    /// The named sections (not [`HudSection::Set`]) in pin order.
    pub const NAMED: [HudSection; 4] = [
        HudSection::HiSec,
        HudSection::Misc,
        HudSection::Quarantine,
        HudSection::SpyHunt,
    ];

    /// The pinned section-name literal.
    pub fn pin(self) -> Option<Pin> {
        let (rva, sha16, len) = match self {
            HudSection::Set => return None,
            HudSection::HiSec => (0x3d72f0, "7e4aa3c2bf2bd36b", 8),
            HudSection::Misc => (0x3ece74, "5cb0b42660589925", 13),
            HudSection::Quarantine => (0x3d8a1c, "f24a1d904fd1b482", 10),
            HudSection::SpyHunt => (0x3d50dc, "ca06af9676e22991", 15),
        };
        Some(Pin {
            what: "HUD layout section",
            rva,
            sha16,
            len,
        })
    }
}

