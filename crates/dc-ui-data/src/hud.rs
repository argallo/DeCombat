/// The HUD key and literal texts of the user's CShell.dll.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct HudKeys {
    keys: Vec<String>,
    literals: Vec<String>,
    /// Names of [`HudSection::NAMED`] in order.
    sections: Vec<String>,
}

impl HudKeys {
    /// Reads every key from `Game/CShell.dll` of the client folder `rom`.
    pub fn from_rom(rom: &Path) -> Result<Self, UiDataError> {
        let p = rom.join(CSHELL_REL_PATH[0]).join(CSHELL_REL_PATH[1]);
        Self::from_cshell(&PeFile::from_file(&p)?)
    }

    /// Reads every key from a loaded CShell.dll image; any mismatch means "not the 2009 build".
    pub fn from_cshell(pe: &PeFile) -> Result<Self, UiDataError> {
        let keys = HudKey::all()
            .map(|k| read_pinned(pe, &k.pin()))
            .collect::<Result<Vec<_>, _>>()?;
        let literals = HudLiteral::ALL
            .iter()
            .map(|l| read_pinned(pe, &l.pin()))
            .collect::<Result<Vec<_>, _>>()?;
        let sections = HudSection::NAMED
            .iter()
            .filter_map(|s| s.pin())
            .map(|p| read_pinned(pe, &p))
            .collect::<Result<Vec<_>, _>>()?;
        Ok(HudKeys {
            keys,
            literals,
            sections,
        })
    }

    /// Invented key names for fixtures and tools without a ROM (`hud_key_<n>`, `hud_literal_<n>`; the clock
    /// digit form keeps one `%d`).
    pub fn placeholder() -> Self {
        HudKeys {
            keys: (0..HudKey::COUNT).map(|i| format!("hud_key_{i}")).collect(),
            literals: vec![
                "hud_lit\\clock_%d.dtx".into(),
                "hud_lit\\clock_sep.dtx".into(),
                "hud_literal_2".into(),
                "hud_literal_3".into(),
                "hud_literal_4".into(),
                "hud_literal_5".into(),
                "%shud_literal_6.dtx".into(),
                "hud_lit\\bomb_%d.dtx".into(),
                "hud_lit\\bomb_icon.dtx".into(),
                "hud_lit\\bomb_sep.dtx".into(),
            ],
            sections: (0..HudSection::NAMED.len())
                .map(|i| format!("hud_section_{i}"))
                .collect(),
        }
    }

    /// The name of a named section (`None` for [`HudSection::Set`]).
    pub fn section(&self, s: HudSection) -> Option<&str> {
        let i = HudSection::NAMED.iter().position(|x| *x == s)?;
        self.sections.get(i).map(String::as_str)
    }

    pub fn key(&self, k: HudKey) -> &str {
        &self.keys[k as usize]
    }

    pub fn literal(&self, l: HudLiteral) -> &str {
        let i = HudLiteral::ALL.iter().position(|x| *x == l).unwrap_or(0);
        &self.literals[i]
    }
}

/// The HUD values of one layout set, read the way the client's accessors read them: the key in set `set`,
/// else in set 0; a missing key or a value of the wrong form is `None` (the client's getters then return their
/// zero default).
// EVIDENCE: cshell+0x4bce0 (set probe and set-0 fallback), cshell+0x5a6c0 (pair getter: (0, 0) when absent)
#[derive(Clone, Copy, Debug)]
pub struct HudView<'a> {
    pub table: &'a LayoutTable,
    pub keys: &'a HudKeys,
    pub set: u32,
}

impl<'a> HudView<'a> {
    pub fn new(table: &'a LayoutTable, keys: &'a HudKeys, set: u32) -> Self {
        HudView { table, keys, set }
    }

    pub fn raw(&self, k: HudKey) -> Option<&'a str> {
        match k.section() {
            HudSection::Set => self.table.hud_raw(self.set, self.keys.key(k)),
            named => self
                .table
                .section(self.keys.section(named)?)?
                .raw(self.keys.key(k)),
        }
    }

    pub fn value(&self, k: HudKey) -> Option<Value> {
        self.raw(k).map(parse_value)
    }

    /// String form (lenient like [`crate::SectionView::string`]); an empty value is `None`.
    /// The value of key `k` read in the named section `sec` instead of its own (the infection element reads some
    /// keys of the round block in its own section, cshell+0xb29c0).
    pub fn raw_in(&self, sec: HudSection, k: HudKey) -> Option<&'a str> {
        self.table
            .section(self.keys.section(sec)?)?
            .raw(self.keys.key(k))
    }

    /// [`HudView::text`] of `k` in section `sec`.
    pub fn text_in(&self, sec: HudSection, k: HudKey) -> Option<&'a str> {
        self.raw_in(sec, k).map(str::trim).filter(|s| !s.is_empty())
    }

    /// [`HudView::pair`] of `k` in section `sec`.
    pub fn pair_in(&self, sec: HudSection, k: HudKey) -> Option<[i32; 2]> {
        match parse_value(self.raw_in(sec, k)?) {
            Value::Pair(p) => Some(p),
            _ => None,
        }
    }

    pub fn text(&self, k: HudKey) -> Option<&'a str> {
        self.raw(k).map(str::trim).filter(|s| !s.is_empty())
    }

    pub fn int(&self, k: HudKey) -> Option<i32> {
        match self.value(k)? {
            Value::Int(i) => Some(i),
            _ => None,
        }
    }

    pub fn real(&self, k: HudKey) -> Option<f64> {
        match self.value(k)? {
            Value::Int(i) => Some(i as f64),
            Value::Real(f) => Some(f),
            _ => None,
        }
    }

    pub fn pair(&self, k: HudKey) -> Option<[i32; 2]> {
        match self.value(k)? {
            Value::Pair(p) => Some(p),
            _ => None,
        }
    }

    /// A colour key: three components 0..255.
    pub fn colour(&self, k: HudKey) -> Option<[f64; 3]> {
        match self.value(k)? {
            Value::Vec3(v) => Some(v),
            _ => None,
        }
    }

    /// Colour key plus alpha key packed the way the colour accessors pack them: each component truncated to a
    /// byte, alpha 1.0 when the alpha key is absent. Returned as straight RGBA.
    // EVIDENCE: cshell+0x514d0 (colour vector, alpha real with default 1.0, four truncations, ARGB packing)
    pub fn rgba(&self, colour: HudKey, alpha: Option<HudKey>) -> Option<[u8; 4]> {
        let c = self.colour(colour)?;
        let a = alpha.and_then(|k| self.real(k)).unwrap_or(1.0) * 255.0;
        let b = |v: f64| v.clamp(0.0, 255.0) as u8;
        Some([b(c[0]), b(c[1]), b(c[2]), b(a)])
    }
}

