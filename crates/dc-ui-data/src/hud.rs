//! Keys of the in-match HUD: the layout-table keys the 2009 HUD elements read for the parts DeCombat draws
//! (health / armour, ammunition, kill feed, team score, scoreboard, damage indicator, respawn wait, chat log),
//! plus the few code literals those elements use (round-clock digit textures, two weapon-row keys).
//!
//! ROM model, as in [`crate::names`]: no key text is in this tree. Every key is read from the user's own
//! `Game/CShell.dll` at the rva of the literal the element's code pushes, and accepted only when its length
//! and SHA-256 prefix match the pin. [`HudView`] then reads the values from the HUD layout set with the
//! client's fallback to set 0.
//!
//! The variant names are ours. Each pin carries the rva of the code that reads the key (an accessor of the
//! layout manager, or the element's layout routine) as its evidence.
// SPEC: FMT_CRES_UI.md §6.1 (value forms), §6.2 (HUD keys fall back to set 0), §8 (HUD elements)
// EVIDENCE: cshell+0x4bce0 and the accessor family cshell+0x4bf70..0x56b30 (one key each: probe set N, else set 0)

