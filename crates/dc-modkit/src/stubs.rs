//! Generators for the editor files `scaffold` writes next to a mod: `.luarc.json` and the
//! EmmyLua/LuaLS type stubs `dc_mod_api.d.lua`.
//!
//! Every name and number here is derived from `dc-mod-lua` (domain list, limits) or from the
//! capability table `ModHost` builds (`host.rs::build_mod_capability_table`), so the stubs cannot
//! silently drift from the runtime. The stubs are comment-only Lua, so `lint` never flags them.
// DOC: docs/MODDING_GUIDE.md section 9

use dc_mod_lua::sandbox::DEFAULT_MAX_LOG_LINES;
use dc_mod_lua::{
    CONTENT_DOMAINS, DEFAULT_CIRCUIT_BREAKER_THRESHOLD, DEFAULT_INSTRUCTION_LIMIT,
    DEFAULT_MAX_CALL_DEPTH, DEFAULT_MAX_STRING_BYTES, DEFAULT_MEMORY_LIMIT, MAP_DESCRIPTION_MAX,
    MAP_ID_MAX, MAP_NAME_MAX, PLAYERS_RANGE, ROUND_SECONDS_RANGE,
};

/// Globals the sandbox does not provide. LuaLS is told to hide them (`runtime.builtin`).
pub const HIDDEN_BUILTINS: &[&str] = &[
    "io",
    "os",
    "debug",
    "package",
    "coroutine",
    "load",
    "loadstring",
    "loadfile",
    "dofile",
    "collectgarbage",
    "getfenv",
    "setfenv",
];

pub fn generate_luarc_json() -> String {
    let mut builtin = String::new();
    for (i, name) in HIDDEN_BUILTINS.iter().enumerate() {
        if i > 0 {
            builtin.push_str(",\n");
        }
        builtin.push_str(&format!("    \"{}\": \"disable\"", name));
    }
    format!(
        r#"{{
  "$schema": "https://raw.githubusercontent.com/LuaLS/vscode-lua/master/setting/schema.json",
  "runtime.version": "Lua 5.4",
  "runtime.path": ["?.lua", "?/init.lua"],
  "runtime.builtin": {{
{builtin}
  }},
  "workspace.library": ["dc_mod_api.d.lua"],
  "workspace.checkThirdParty": false,
  "diagnostics.globals": ["unpack"],
  "completion.requireSeparator": "."
}}
"#
    )
}

pub fn generate_ca_mod_api_d_lua() -> String {
    let mut domains_fields = String::new();
    for d in CONTENT_DOMAINS {
        domains_fields.push_str(&format!("---@field {} ModContentRegistry\n", d));
    }
    let domain_list = CONTENT_DOMAINS.join(", ");
    format!(
        r#"---@meta
-- Combat Arms mod API for the DeCombat sandboxed Lua runtime (EmmyLua / LuaLS type stubs).
-- Generated by `dc-modkit scaffold`; regenerate rather than edit.
--
-- Entry contract: main.lua must return a function that receives the capability table.
--
--     ---@param mod ModCapability
--     return function(mod)
--         mod.content.weapons:patch(145, {{ AmmoDamage = 38 }})
--     end
--
-- Capability methods accept both `t:method(...)` and `t.method(...)`.
-- Data crossing the host boundary (patch/override values, hook contexts and results, save values)
-- must be plain data: nil, boolean, number, string and tables of those. Functions, userdata and
-- cyclic or very deep tables are rejected with an error.
--
-- Sandbox limits (host configuration, a mod cannot change them):
--   * Instruction budget: {instr} VM instructions per host-to-Lua call (mod init, each hook stage,
--     each event listener). pcall/xpcall re-raise the kill, so it cannot be swallowed.
--   * Memory: {mem} bytes of Lua heap for the whole host.
--   * string.rep and string.format results are capped at {strcap} bytes.
--   * Call depth: more than {depth} nested Lua frames is killed.
--   * print() is captured per mod, at most {logs} lines, never written to stdout.
--   * Circuit breaker: after {breaker} recorded errors a mod's hooks and listeners are switched off.
--   * Precompiled (binary) chunks are refused, in main.lua and in required modules.
--   * require("a.b") loads <mod dir>/a/b.lua or <mod dir>/a/b/init.lua only: dot-separated names of
--     [A-Za-z0-9_-], no slashes, no "..", no absolute paths, no symlink escapes.
--   * Not available: os, io, debug, package, coroutine, load, loadstring, loadfile, dofile,
--     collectgarbage, getfenv, setfenv, string.dump, math.randomseed. setmetatable refuses
--     metatables that carry __gc.
--   * Available: the base functions assert, error, getmetatable, ipairs, next, pairs, pcall,
--     rawequal, rawget, rawlen, rawset, select, setmetatable, tonumber, tostring, type, xpcall,
--     plus unpack (= table.unpack), and the string, table, math and utf8 libraries.
-- Each mod gets private copies of those libraries and its own _G.
--
-- Declared capabilities (manifest.json "capabilities"; the host refuses any use beyond the list and
-- the mod then fails to load):
--   * content.<domain>   mod.content.<domain>:patch/register/override/get ({domain_list})
--   * hooks.<namespace>  mod.hooks:wrap/on("<namespace>.<name>", ...) for lobby, combat, render, hud
--   * events             mod.events:on
--   * save               mod.save:get/set
--   * assets             mod.assets:path
-- hooks.render and hooks.hud load only for mods declared in a server's mod set (never local mods).

-- ---------------------------------------------------------------------------------------------
-- Extensions to the standard libraries
-- ---------------------------------------------------------------------------------------------

---@class mathlib
---Clamps `x` into the closed range [lo, hi] (DeCombat extension, not part of Lua).
---Returns a float, so math.clamp(5, 0, 10) is 5.0. Raises an error for non-numeric arguments.
---@field clamp fun(x: number, lo: number, hi: number): number

-- ---------------------------------------------------------------------------------------------
-- mod.content.<domain>
-- ---------------------------------------------------------------------------------------------

---A record: string and integer keys with plain-data values.
---@alias ModRecord table<string|integer, any>

---One content domain. The domains are: {domain_list}.
---Record ids are non-empty strings or numbers; 145 and "145" address the same record.
---@class ModContentRegistry
---Deep-merges `partial` into the record `id` and returns a copy of the merged record. A record that
---does not exist yet is created with `id = id`. Raises if `partial` is not a table.
---@field patch fun(self: ModContentRegistry, id: integer|string, partial: ModRecord): ModRecord
---Stores a new record and returns its id. Without an `id` field the host assigns the next free
---id (starting at 10000 per domain). Replaces a record with the same id.
---@field register fun(self: ModContentRegistry, def: ModRecord): integer|string
---Sets `key` to `value` for the whole domain. A table value also replaces the record `key`.
---@field override fun(self: ModContentRegistry, key: integer|string, value: any)
---Returns a copy of the record or override stored under `id`, or nil.
---@field get fun(self: ModContentRegistry, id: integer|string): any

---@class ModContentDomains
{domains_fields}
---A community map (`mod.content.maps:register(record)`, capability `content.maps`; MAP-4). The host checks the
---record at load: the keys below and no others, the required ones present, the world this mod's own
---`assets/...dat` as `mod.assets:path` returns it, every mode a DeCombat mode name ({mode_names}).
---`:patch(id, partial)` changes a map another mod registered (the world stays the owner's); `:override` is refused.
---@class ModMapRecord
---@field id string               the map key: a-z 0-9 _, 1..{id_max} characters (required)
---@field name string             the room-list label, 1..{name_max} characters (required)
---@field world string            mod.assets:path("assets/maps/<key>.dat") (required)
---@field modes string[]          non-empty list of mode names, no duplicates (required)
---@field description string|nil  at most {desc_max} characters
---@field goals table<string, integer>|nil  default goal per mode (a mode of `modes`), positive
---@field round_seconds integer|nil  {rs_lo}..{rs_hi}
---@field picture string|nil      texture path (ROM path or mod.assets:path)
---@field loading string|nil      texture path
---@field radar table|nil         {{ picture = string, min = {{ x, z }}, max = {{ x, z }} }}
---@field players table|nil       {{ min = integer, max = integer }}, {pl_lo}..{pl_hi}, min <= max

-- ---------------------------------------------------------------------------------------------
-- mod.hooks, mod.events
-- ---------------------------------------------------------------------------------------------

---A hook stage. `base(ctx)` runs the next stage inward (finally the host's own calculation) and
---returns its result; the stage returns the (possibly changed) result. `ctx` is a copy of the data
---the host passes in. A stage that raises is skipped (the chain continues with the stage inside it)
---and the error is recorded against the mod.
---@alias ModHookStage fun(base: fun(ctx: table): any, ctx: table): any

---@class ModHooks
---Wraps the host calculation `hook_name` (for example "lobby.calc_exp_gp" or "combat.damage").
---Stages are ordered by mod priority, then load order: the lowest sits closest to the host
---calculation, the highest (last loaded) is outermost and sees the final result.
---@field wrap fun(self: ModHooks, hook_name: string, stage: ModHookStage)
---Same registration as `wrap` (the runtime treats both verbs identically).
---@field on fun(self: ModHooks, hook_name: string, stage: ModHookStage)

---@class ModEvents
---Registers a listener for the event `topic` (for example "match.end"). The listener gets its
---own copy of the event data and runs in its own protected call; its return value is ignored.
---@field on fun(self: ModEvents, topic: string, listener: fun(ctx: table))

-- ---------------------------------------------------------------------------------------------
-- mod.save, mod.options, mod.assets
-- ---------------------------------------------------------------------------------------------

---Per-mod persistent key/value store. Values must be JSON-representable.
---@class ModSave
---@field get fun(self: ModSave, key: string): any
---Stores `value` under `key`; nil deletes the key.
---@field set fun(self: ModSave, key: string, value: any)

---User-tunable settings.
---@class ModOptions
---Declares the options. `schema` maps option name to a spec table `{{ type = ..., default = ... }}`
---(the `default` is the initial value) or directly to a default value. Existing values are kept.
---@field define fun(self: ModOptions, schema: table<string, table|any>)
---Current value of the option, or nil when undefined.
---@field get fun(self: ModOptions, key: string): any
---@field set fun(self: ModOptions, key: string, value: any)

---@class ModAssets
---Validates a path relative to the mod directory and returns the virtual path
---"@mod:<mod id>/<clean path>". Raises for empty, absolute, drive-qualified or ".." paths.
---@field path fun(self: ModAssets, rel_path: string): string

-- ---------------------------------------------------------------------------------------------
-- The capability table
-- ---------------------------------------------------------------------------------------------

---What `mod.find` returns for a loaded mod.
---@class ModPeerInfo
---@field id string
---@field name string
---@field version string
---@field exports table

---@class ModCapability
---@field id string                 manifest id
---@field name string               manifest name
---@field version string            manifest version, "major.minor.patch"
---@field api integer               manifest api level
---@field priority integer          manifest priority (lower runs earlier)
---@field kind string              manifest kind: "server_rules", "shared" or "client_visual"
---@field content ModContentDomains
---@field hooks ModHooks
---@field events ModEvents
---@field save ModSave
---@field options ModOptions
---@field assets ModAssets
---The player's values of the manifest's settings (read-only; client_visual mods).
---@field settings table<string, string|boolean|number>
---Table other mods read through `mod.find(id).exports`. Assigning a new table to `mod.exports`
---during init is honoured.
---@field exports table
---Looks up an already loaded mod (declare it in `dependencies` to be sure it loads first). Returns nil
---when it is not loaded.
---@field find fun(self: ModCapability, other_mod_id: string): ModPeerInfo|nil
"#,
        instr = DEFAULT_INSTRUCTION_LIMIT,
        mem = DEFAULT_MEMORY_LIMIT,
        strcap = DEFAULT_MAX_STRING_BYTES,
        depth = DEFAULT_MAX_CALL_DEPTH,
        logs = DEFAULT_MAX_LOG_LINES,
        breaker = DEFAULT_CIRCUIT_BREAKER_THRESHOLD,
        domain_list = domain_list,
        mode_names = dc_config::modes::MODE_NAMES.join(", "),
        id_max = MAP_ID_MAX,
        name_max = MAP_NAME_MAX,
        desc_max = MAP_DESCRIPTION_MAX,
        rs_lo = ROUND_SECONDS_RANGE.0,
        rs_hi = ROUND_SECONDS_RANGE.1,
        pl_lo = PLAYERS_RANGE.0,
        pl_hi = PLAYERS_RANGE.1,
        domains_fields = domains_fields,
    )
}
