//! The Hacking Mod's Mods-panel picture, drawn here from nothing (MOD-20, MOD-27).
//!
//! Every shape, colour and letter is in this file: no ROM data, game font, HUD art, game model or screenshot goes
//! in, and the figures are plain mannequins of our own. The picture is 4x supersampled and uses only + - * / and
//! sqrt, so it comes out the same everywhere. The test compares it with the committed file; after a look change run
//! `DC_HACKING_ART_WRITE=1 python cargo_env.py cargo test -p dc-client --test hacking_art` to write it again.
// DC-DEFAULT: MOD-27 the package picture is generated by our own code, see DC_DEFAULTS.md

use std::path::Path;

const W: usize = 1120;
const H: usize = 630;
const SS: usize = 4;

type P = (f32, f32);
type Rgb = [u8; 3];

enum Shape {
    Poly(Vec<P>),
    Capsule(P, P, f32),
    Ellipse(P, f32, f32),
}

struct Canvas {
    px: Vec<Rgb>,
}

impl Canvas {
    fn new() -> Self {
        Canvas { px: vec![[0; 3]; W * SS * H * SS] }
    }

    /// Paints the union of `shapes` once, so overlapping parts of one see-through figure do not darken twice.
    fn paint(&mut self, shapes: &[Shape], colour: Rgb, alpha: f32) {
        let (mut x0, mut y0, mut x1, mut y1) = (f32::MAX, f32::MAX, f32::MIN, f32::MIN);
        let mut grow = |x: f32, y: f32, r: f32| {
            x0 = x0.min(x - r);
            y0 = y0.min(y - r);
            x1 = x1.max(x + r);
            y1 = y1.max(y + r);
        };
        for s in shapes {
            match s {
                Shape::Poly(p) => p.iter().for_each(|q| grow(q.0, q.1, 0.0)),
                Shape::Capsule(a, b, r) => {
                    grow(a.0, a.1, *r);
                    grow(b.0, b.1, *r);
                }
                Shape::Ellipse(c, rx, ry) => grow(c.0, c.1, rx.max(*ry)),
            }
        }
        let s = SS as f32;
        let xa = ((x0 * s).floor().max(0.0)) as usize;
        let ya = ((y0 * s).floor().max(0.0)) as usize;
        let xb = ((x1 * s).ceil().max(0.0) as usize).min(W * SS);
        let yb = ((y1 * s).ceil().max(0.0) as usize).min(H * SS);
        if xa >= xb || ya >= yb {
            return;
        }
        let mut row = vec![false; xb - xa];
        for y in ya..yb {
            row.iter_mut().for_each(|c| *c = false);
            let fy = (y as f32 + 0.5) / s;
            for shape in shapes {
                mark_row(shape, fy, xa, &mut row);
            }
            let line = &mut self.px[y * W * SS + xa..y * W * SS + xb];
            for (d, on) in line.iter_mut().zip(&row) {
                if *on {
                    for i in 0..3 {
                        d[i] = (d[i] as f32 * (1.0 - alpha) + colour[i] as f32 * alpha + 0.5) as u8;
                    }
                }
            }
        }
    }

    fn rect(&mut self, x0: f32, y0: f32, x1: f32, y1: f32, colour: Rgb, alpha: f32) {
        self.paint(&[rect(x0, y0, x1, y1)], colour, alpha);
    }

    /// A frame of thickness `t` inside the rectangle.
    #[allow(clippy::too_many_arguments)]
    fn border(&mut self, x0: f32, y0: f32, x1: f32, y1: f32, t: f32, colour: Rgb, alpha: f32) {
        self.paint(
            &[
                rect(x0, y0, x1, y0 + t),
                rect(x0, y1 - t, x1, y1),
                rect(x0, y0 + t, x0 + t, y1 - t),
                rect(x1 - t, y0 + t, x1, y1 - t),
            ],
            colour,
            alpha,
        );
    }

    fn down(&self) -> Vec<u8> {
        let mut out = Vec::with_capacity(W * H * 3);
        for y in 0..H {
            for x in 0..W {
                let mut sum = [0u32; 3];
                for sy in 0..SS {
                    for sx in 0..SS {
                        let p = self.px[(y * SS + sy) * W * SS + x * SS + sx];
                        for i in 0..3 {
                            sum[i] += p[i] as u32;
                        }
                    }
                }
                let n = (SS * SS) as u32;
                out.extend(sum.iter().map(|v| ((v + n / 2) / n) as u8));
            }
        }
        out
    }
}

/// Sets the samples of one canvas row that `shape` covers.
fn mark_row(shape: &Shape, fy: f32, xa: usize, row: &mut [bool]) {
    let s = SS as f32;
    let mut span = |l: f32, r: f32| {
        // sample x + 0.5 lies in [l*s, r*s)
        let a = ((l * s - 0.5).ceil().max(xa as f32)) as usize - xa;
        let b = (((r * s - 0.5).ceil().max(xa as f32)) as usize - xa).min(row.len());
        if a < b {
            row[a..b].iter_mut().for_each(|c| *c = true);
        }
    };
    match shape {
        Shape::Poly(p) => {
            let mut hits = Vec::with_capacity(8);
            for i in 0..p.len() {
                let (a, b) = (p[i], p[(i + 1) % p.len()]);
                if (a.1 <= fy) != (b.1 <= fy) {
                    hits.push(a.0 + (fy - a.1) / (b.1 - a.1) * (b.0 - a.0));
                }
            }
            hits.sort_by(f32::total_cmp);
            for pair in hits.chunks_exact(2) {
                span(pair[0], pair[1]);
            }
        }
        Shape::Capsule(a, b, r) => {
            // A row of a capsule is one span: its extent is found by the distance to the segment, sample by sample.
            let (dx, dy) = (b.0 - a.0, b.1 - a.1);
            let len = dx * dx + dy * dy;
            if fy < a.1.min(b.1) - r || fy > a.1.max(b.1) + r {
                return;
            }
            let inside = |x: f32| {
                let t = if len > 0.0 { (((x - a.0) * dx + (fy - a.1) * dy) / len).clamp(0.0, 1.0) } else { 0.0 };
                let (ex, ey) = (x - a.0 - t * dx, fy - a.1 - t * dy);
                ex * ex + ey * ey <= r * r
            };
            let step = 1.0 / s;
            let first = ((a.0.min(b.0) - r) * s).floor();
            let n = (((a.0.max(b.0) + r) * s).ceil() - first) as i32;
            let (mut l, mut h) = (f32::MAX, f32::MIN);
            for i in 0..=n {
                let x = (first + i as f32 + 0.5) / s;
                if inside(x) {
                    l = l.min(x);
                    h = h.max(x);
                }
            }
            if l <= h {
                span(l, h + step);
            }
        }
        Shape::Ellipse(c, rx, ry) => {
            let v = (fy - c.1) / ry;
            let q = 1.0 - v * v;
            if q > 0.0 {
                let d = rx * q.sqrt();
                span(c.0 - d, c.0 + d);
            }
        }
    }
}

fn rect(x0: f32, y0: f32, x1: f32, y1: f32) -> Shape {
    Shape::Poly(vec![(x0, y0), (x1, y0), (x1, y1), (x0, y1)])
}

// ---- our own letters: strokes on a 4 x 6 grid, chamfered corners ----

fn glyph(c: char) -> &'static [&'static [P]] {
    match c {
        'A' => &[&[(0., 6.), (0., 1.5), (1.5, 0.), (2.5, 0.), (4., 1.5), (4., 6.)], &[(0., 4.), (4., 4.)]],
        'B' => &[&[(0., 3.), (3., 3.), (4., 2.), (4., 1.), (3., 0.), (0., 0.), (0., 6.), (3., 6.), (4., 5.), (4., 4.), (3., 3.)]],
        'C' => &[&[(4., 1.), (3., 0.), (1., 0.), (0., 1.), (0., 5.), (1., 6.), (3., 6.), (4., 5.)]],
        'E' => &[&[(4., 0.), (0., 0.), (0., 6.), (4., 6.)], &[(0., 3.), (3., 3.)]],
        'H' => &[&[(0., 0.), (0., 6.)], &[(4., 0.), (4., 6.)], &[(0., 3.), (4., 3.)]],
        'I' => &[&[(2., 0.), (2., 6.)], &[(1., 0.), (3., 0.)], &[(1., 6.), (3., 6.)]],
        'K' => &[&[(0., 0.), (0., 6.)], &[(4., 0.), (0., 3.5)], &[(1.4, 2.3), (4., 6.)]],
        'L' => &[&[(0., 0.), (0., 6.), (4., 6.)]],
        'M' => &[&[(0., 6.), (0., 0.), (2., 3.2), (4., 0.), (4., 6.)]],
        'N' => &[&[(0., 6.), (0., 0.), (4., 6.), (4., 0.)]],
        'O' => &[&[(1., 0.), (3., 0.), (4., 1.), (4., 5.), (3., 6.), (1., 6.), (0., 5.), (0., 1.), (1., 0.)]],
        'P' => &[&[(0., 6.), (0., 0.), (3., 0.), (4., 1.), (4., 2.5), (3., 3.5), (0., 3.5)]],
        'R' => &[&[(0., 6.), (0., 0.), (3., 0.), (4., 1.), (4., 2.5), (3., 3.5), (0., 3.5)], &[(2.2, 3.5), (4., 6.)]],
        'S' => &[&[(4., 1.), (3., 0.), (1., 0.), (0., 1.), (0., 2.), (1., 3.), (3., 3.), (4., 4.), (4., 5.), (3., 6.), (1., 6.), (0., 5.)]],
        'T' => &[&[(0., 0.), (4., 0.)], &[(2., 0.), (2., 6.)]],
        'X' => &[&[(0., 0.), (4., 6.)], &[(4., 0.), (0., 6.)]],
        'Y' => &[&[(0., 0.), (2., 3.), (4., 0.)], &[(2., 3.), (2., 6.)]],
        '1' => &[&[(0.9, 1.3), (2.2, 0.), (2.2, 6.)], &[(0.9, 6.), (3.5, 6.)]],
        '2' => &[&[(0., 1.), (1., 0.), (3., 0.), (4., 1.), (4., 2.), (0., 6.), (4., 6.)]],
        '3' => &[&[(0., 1.), (1., 0.), (3., 0.), (4., 1.), (4., 2.), (3., 3.), (1.5, 3.)], &[(3., 3.), (4., 4.), (4., 5.), (3., 6.), (1., 6.), (0., 5.)]],
        ' ' => &[],
        other => panic!("no letter for {other:?}"),
    }
}

const ADVANCE: f32 = 5.5;

fn text_width(t: &str, size: f32) -> f32 {
    let u = size / 6.0;
    (t.chars().count() as f32 * ADVANCE - (ADVANCE - 4.0)) * u
}

/// Centred on `cx`, cap height `size`, top at `y`.
fn text(c: &mut Canvas, t: &str, cx: f32, y: f32, size: f32, weight: f32, colour: Rgb) {
    let u = size / 6.0;
    let mut x = cx - text_width(t, size) / 2.0;
    let mut shapes = Vec::new();
    for ch in t.chars() {
        for line in glyph(ch) {
            for seg in line.windows(2) {
                let a = (x + seg[0].0 * u, y + seg[0].1 * u);
                let b = (x + seg[1].0 * u, y + seg[1].1 * u);
                shapes.push(Shape::Capsule(a, b, weight / 2.0));
            }
        }
        x += ADVANCE * u;
    }
    c.paint(&shapes, colour, 1.0);
}

// ---- our own mannequin ----

struct Figure {
    cx: f32,
    foot: f32,
    h: f32,
}

// The joints, in figure heights: x from the centre line, y up from the floor. The left and right sides mirror.
const HEAD: P = (0.0, 0.925);
const HEAD_R: f32 = 0.072;
const NECK: P = (0.0, 0.835);
const SHOULDER: P = (0.125, 0.785);
const ELBOW: P = (0.175, 0.615);
const HAND: P = (0.165, 0.445);
const PELVIS: P = (0.0, 0.5);
const HIP: P = (0.07, 0.49);
const KNEE: P = (0.09, 0.27);
const ANKLE: P = (0.1, 0.05);
const TOE: P = (0.135, 0.018);

impl Figure {
    fn at(&self, j: P, side: f32) -> P {
        (self.cx + j.0 * side * self.h, self.foot - j.1 * self.h)
    }

    /// The solid body, `grow` pixels fatter all round.
    fn body(&self, grow: f32) -> Vec<Shape> {
        let h = self.h;
        let mut s = vec![
            Shape::Ellipse(self.at(HEAD, 1.0), HEAD_R * h * 0.9 + grow, HEAD_R * h + grow),
            Shape::Capsule(self.at(NECK, 1.0), self.at((0.0, 0.88), 1.0), 0.034 * h + grow),
        ];
        let torso = [
            self.at((0.135, 0.805), -1.0),
            self.at((0.135, 0.805), 1.0),
            self.at((0.085, 0.60), 1.0),
            self.at((0.098, 0.47), 1.0),
            self.at((0.098, 0.47), -1.0),
            self.at((0.085, 0.60), -1.0),
        ];
        for i in 0..torso.len() {
            s.push(Shape::Capsule(torso[i], torso[(i + 1) % torso.len()], grow.max(1.0)));
        }
        s.push(Shape::Poly(torso.to_vec()));
        for side in [-1.0, 1.0] {
            s.push(Shape::Capsule(self.at(SHOULDER, side), self.at(ELBOW, side), 0.036 * h + grow));
            s.push(Shape::Capsule(self.at(ELBOW, side), self.at(HAND, side), 0.029 * h + grow));
            s.push(Shape::Capsule(self.at(HIP, side), self.at(KNEE, side), 0.05 * h + grow));
            s.push(Shape::Capsule(self.at(KNEE, side), self.at(ANKLE, side), 0.037 * h + grow));
            s.push(Shape::Capsule(self.at(ANKLE, side), self.at(TOE, side), 0.026 * h + grow));
        }
        s
    }

    fn bones(&self) -> Vec<(P, P)> {
        let top = self.at((0.0, 0.875), 1.0);
        let neck = self.at(NECK, 1.0);
        let pelvis = self.at(PELVIS, 1.0);
        let mut b = vec![(top, neck), (neck, pelvis)];
        for side in [-1.0, 1.0] {
            b.push((neck, self.at(SHOULDER, side)));
            b.push((self.at(SHOULDER, side), self.at(ELBOW, side)));
            b.push((self.at(ELBOW, side), self.at(HAND, side)));
            b.push((pelvis, self.at(HIP, side)));
            b.push((self.at(HIP, side), self.at(KNEE, side)));
            b.push((self.at(KNEE, side), self.at(ANKLE, side)));
        }
        b
    }

    fn joints(&self) -> Vec<P> {
        let mut j = vec![self.at(NECK, 1.0), self.at(PELVIS, 1.0)];
        for side in [-1.0, 1.0] {
            for p in [SHOULDER, ELBOW, HAND, HIP, KNEE, ANKLE] {
                j.push(self.at(p, side));
            }
        }
        j
    }

    fn top(&self) -> f32 {
        self.foot - (HEAD.1 + HEAD_R) * self.h
    }
}

// ---- the palette ----

const CEILING: Rgb = [15, 18, 26];
const BACK_WALL: Rgb = [30, 37, 50];
const SIDE_WALL: Rgb = [22, 27, 38];
const FLOOR: Rgb = [18, 21, 29];
const LINE: Rgb = [44, 53, 70];
const LIGHT: Rgb = [136, 164, 196];
const GLASS: Rgb = [108, 150, 190];
const FRAME: Rgb = [50, 61, 80];
const FRAME_HI: Rgb = [92, 110, 136];
const FRAME_LO: Rgb = [26, 32, 44];
const SHADE: Rgb = [7, 9, 14];
const INK: Rgb = [230, 236, 244];
const MUTED: Rgb = [136, 150, 170];
const CHAMS_FRONT: Rgb = [232, 58, 92];
const CHAMS_RIM: Rgb = [255, 190, 150];
const BONE: Rgb = [70, 240, 180];
const BOX: Rgb = [255, 200, 60];
const HEALTH: Rgb = [96, 224, 120];

const PANEL: (f32, f32, f32, f32) = (66.0, 62.0, 1054.0, 540.0);

fn room(c: &mut Canvas) {
    let (w, h) = (W as f32, H as f32);
    let (bx0, by0, bx1, by1) = (290.0, 140.0, 830.0, 410.0);
    c.rect(0.0, 0.0, w, h, CEILING, 1.0);
    c.rect(bx0, by0, bx1, by1, BACK_WALL, 1.0);
    c.paint(&[Shape::Poly(vec![(0.0, 0.0), (bx0, by0), (bx0, by1), (0.0, h)])], SIDE_WALL, 1.0);
    c.paint(&[Shape::Poly(vec![(w, 0.0), (bx1, by0), (bx1, by1), (w, h)])], SIDE_WALL, 1.0);
    c.paint(&[Shape::Poly(vec![(0.0, h), (bx0, by1), (bx1, by1), (w, h)])], FLOOR, 1.0);
    // the corners of the room
    for (a, b) in [((0.0, 0.0), (bx0, by0)), ((w, 0.0), (bx1, by0)), ((0.0, h), (bx0, by1)), ((w, h), (bx1, by1))] {
        c.paint(&[Shape::Capsule(a, b, 1.2)], LINE, 1.0);
    }
    c.border(bx0, by0, bx1, by1, 2.0, LINE, 1.0);
    // floor boards running to the back wall
    for i in 1..8 {
        let t = i as f32 / 8.0;
        c.paint(&[Shape::Capsule((w * t, h), (bx0 + (bx1 - bx0) * t, by1), 0.9)], LINE, 0.55);
    }
    // a light strip along each side wall, a quarter of the way down it
    let wall = |x_near: f32, x_far: f32, t: f32, v: f32| {
        let (near, far) = (h * v, by0 + (by1 - by0) * v);
        (x_near + (x_far - x_near) * t, near + (far - near) * t)
    };
    for (near, far) in [(0.0, bx0), (w, bx1)] {
        let strip = vec![wall(near, far, 0.0, 0.26), wall(near, far, 0.92, 0.26), wall(near, far, 0.92, 0.285), wall(near, far, 0.0, 0.285)];
        c.paint(&[Shape::Poly(strip)], LIGHT, 0.3);
    }
    // a stripe on the back wall
    c.rect(bx0 + 2.0, by0 + 92.0, bx1 - 2.0, by0 + 98.0, LIGHT, 0.28);
}

fn panel_glass(c: &mut Canvas) {
    let (x0, y0, x1, y1) = PANEL;
    c.rect(x0, y0, x1, y1, GLASS, 0.17);
    // flat slanted sheen
    let band = |x: f32, wide: f32| Shape::Poly(vec![(x + 120.0, y0), (x + 120.0 + wide, y0), (x + wide, y1), (x, y1)]);
    c.paint(&[band(x0 + 26.0, 120.0), band(x0 + 176.0, 34.0)], [200, 225, 245], 0.05);
    c.paint(&[band(x0 + 700.0, 56.0)], [200, 225, 245], 0.05);
}

fn panel_frame(c: &mut Canvas) {
    let (x0, y0, x1, y1) = PANEL;
    let t = 11.0;
    // the shadow it throws on the floor
    c.rect(x0 + 6.0, y1, x1 - 6.0, y1 + 12.0, SHADE, 0.75);
    c.border(x0, y0, x1, y1, t, FRAME, 1.0);
    // the cut edge: light on top and left, dark on the bottom and right
    c.rect(x0, y0, x1, y0 + 2.0, FRAME_HI, 1.0);
    c.rect(x0, y0, x0 + 2.0, y1, FRAME_HI, 1.0);
    c.rect(x0, y1 - 2.0, x1, y1, FRAME_LO, 1.0);
    c.rect(x1 - 2.0, y0, x1, y1, FRAME_LO, 1.0);
    c.border(x0 + t, y0 + t, x1 - t, y1 - t, 2.0, FRAME_LO, 1.0);
}

fn tag(c: &mut Canvas, f: &Figure, top: f32, name: &str, health: f32) {
    let (bw, bh) = (140.0, 12.0);
    let (x0, y0) = (f.cx - bw / 2.0, top - 12.0 - bh);
    text(c, name, f.cx, y0 - 26.0, 18.0, 2.6, INK);
    c.rect(x0, y0, x0 + bw, y0 + bh, SHADE, 0.9);
    c.rect(x0 + 2.0, y0 + 2.0, x0 + 2.0 + (bw - 4.0) * health, y0 + bh - 2.0, HEALTH, 1.0);
}

fn label(c: &mut Canvas, cx: f32, t: &str, colour: Rgb) {
    let size = 26.0;
    let half = text_width(t, size) / 2.0 + 18.0;
    let (y0, y1) = (564.0, 610.0);
    c.rect(cx - half, y0, cx + half, y1, SHADE, 0.85);
    c.rect(cx - half, y0, cx + half, y0 + 4.0, colour, 1.0);
    text(c, t, cx, y0 + 12.0, size, 3.8, colour);
}

fn crosshair(c: &mut Canvas) {
    let (x, y) = (W as f32 / 2.0, H as f32 / 2.0);
    let (gap, len) = (8.0, 13.0);
    for (t, colour, grow) in [(2.0, SHADE, 2.5), (2.0, INK, 0.0)] {
        let half: f32 = t + grow;
        let g = gap - grow;
        let l = gap + len + grow;
        c.paint(
            &[
                rect(x - half, y - l, x + half, y - g),
                rect(x - half, y + g, x + half, y + l),
                rect(x - l, y - half, x - g, y + half),
                rect(x + g, y - half, x + l, y + half),
            ],
            colour,
            1.0,
        );
    }
}

fn caption(c: &mut Canvas) {
    let t = "NO RECOIL ROOMS";
    let (cx, y, size) = (W as f32 / 2.0, 24.0, 16.0);
    text(c, t, cx, y, size, 2.2, MUTED);
    let half = text_width(t, size) / 2.0 + 16.0;
    c.rect(cx - half - 90.0, y + 7.0, cx - half, y + 9.0, LINE, 1.0);
    c.rect(cx + half, y + 7.0, cx + half + 90.0, y + 9.0, LINE, 1.0);
}

fn picture() -> Vec<u8> {
    let mut c = Canvas::new();
    room(&mut c);
    let foot = 524.0;
    let h = 340.0;
    let figs = [Figure { cx: 232.0, foot, h }, Figure { cx: 560.0, foot, h }, Figure { cx: 888.0, foot, h }];
    // Behind the wall: the floor shadows and the dim bodies seen through it.
    for f in &figs {
        c.paint(&[Shape::Ellipse((f.cx, foot + 2.0), 0.24 * h, 10.0)], SHADE, 0.8);
        c.paint(&f.body(0.0), SHADE, 0.72);
    }
    panel_glass(&mut c);
    panel_frame(&mut c);
    // Where a style shows no body of its own, the body stays readable through the wall.
    c.paint(&figs[1].body(0.0), SHADE, 0.4);
    c.paint(&figs[2].body(0.0), SHADE, 0.4);
    // One height for all the tags: just above the box, the tallest of the three styles.
    let tags = figs[2].top() - 8.0;

    // chams: two flat tones, the rim outside the front
    c.paint(&figs[0].body(4.0), CHAMS_RIM, 1.0);
    c.paint(&figs[0].body(0.0), CHAMS_FRONT, 1.0);
    tag(&mut c, &figs[0], tags, "PLAYER 1", 1.0);

    // skeleton: bones, a square head, then joint squares
    let bones: Vec<Shape> = figs[1].bones().into_iter().map(|(a, b)| Shape::Capsule(a, b, 3.5)).collect();
    c.paint(&bones, BONE, 1.0);
    let head = figs[1].at(HEAD, 1.0);
    let r = HEAD_R * h;
    c.border(head.0 - r * 0.9, head.1 - r, head.0 + r * 0.9, head.1 + r, 7.0, BONE, 1.0);
    for (x, y) in figs[1].joints() {
        c.rect(x - 8.0, y - 8.0, x + 8.0, y + 8.0, SHADE, 1.0);
        c.rect(x - 6.0, y - 6.0, x + 6.0, y + 6.0, INK, 1.0);
    }
    tag(&mut c, &figs[1], tags, "PLAYER 2", 0.62);

    // box: fill and border
    let (bl, bt, br, bb) = (figs[2].cx - 0.27 * h, tags, figs[2].cx + 0.27 * h, foot + 4.0);
    c.rect(bl, bt, br, bb, BOX, 0.16);
    c.border(bl, bt, br, bb, 5.0, BOX, 1.0);
    tag(&mut c, &figs[2], bt, "PLAYER 3", 0.28);

    label(&mut c, figs[0].cx, "CHAMS", CHAMS_RIM);
    label(&mut c, figs[1].cx, "SKELETON", BONE);
    label(&mut c, figs[2].cx, "BOX", BOX);
    caption(&mut c);
    crosshair(&mut c);
    c.down()
}

fn encode(rgb: &[u8]) -> Vec<u8> {
    use image::ImageEncoder;
    let mut out = Vec::new();
    image::codecs::png::PngEncoder::new_with_quality(
        &mut out,
        image::codecs::png::CompressionType::Best,
        image::codecs::png::FilterType::Adaptive,
    )
    .write_image(rgb, W as u32, H as u32, image::ExtendedColorType::Rgb8)
    .unwrap();
    out
}

#[test]
fn the_hacking_mod_picture_is_what_this_file_draws() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../examples/mods/hacking_mod/screenshots/main.png");
    let rgb = picture();
    assert_eq!(rgb.len(), W * H * 3);
    if std::env::var_os("DC_HACKING_ART_WRITE").is_some() {
        std::fs::write(&path, encode(&rgb)).unwrap();
    }
    let bytes = std::fs::read(&path).unwrap();
    assert!(bytes.len() < 1 << 20, "{} bytes is over the screenshot limit", bytes.len());
    let got = image::load_from_memory_with_format(&bytes, image::ImageFormat::Png).unwrap().to_rgb8();
    assert_eq!((got.width() as usize, got.height() as usize), (W, H));
    assert!(got.as_raw() == &rgb, "the committed picture differs; see the note at the top of this file");
}
